local root = vim.fn.fnamemodify(debug.getinfo(1, 'S').source:sub(2), ':p:h:h:h')
package.path = root .. '/tests/lib/?.lua;' .. package.path
local T = require('check')

local function line(e)
  return e:lua('return vim.api.nvim_get_current_line()')
end

local function expand(e, trigger)
  e:input('i' .. (trigger or 'forgecall') .. '<C-Space>')
  e:wait('настоящее меню cmp с LuaSnip', function()
    return e:lua([[local c=require('cmp');if not c.visible() then return false end;
      for _,v in ipairs(c.get_entries()) do if v.source.name=='luasnip' then return true end end;return false]])
  end, 10000)
  e:input('<C-j>')
  e:wait('выбрано snippet-предложение', function()
    return e:lua([[local v=require('cmp').get_selected_entry();return v~=nil and v.source.name=='luasnip']])
  end)
  e:input('<CR>')
  e:wait('активное поле в select mode', function() return e:lua('return vim.api.nvim_get_mode().mode') == 's' end)
end

local function leave_field(e)
  -- Ctrl-\ Ctrl-N — штатный выход в normal, не явное сворачивание по Esc.
  e:input('<C-\\><C-n>')
  e:wait('normal mode', function() return e:lua('return vim.api.nvim_get_mode().mode') == 'n' end)
end

local function check(name, fn)
  T.check('IDE-SNIP-1 ' .. name, function()
    local e
    local ok, failure = pcall(function()
      e = require('editor').start(root)
      assert(vim.uv.fs_copyfile(root .. '/tests/e2e/fixtures/snippet-input/forge.code-snippets', e.project .. '/forge.code-snippets'))
      e:input(':edit snippet.txt<CR>i')
      e:wait('insert mode и completion загружены', function() return e:lua('return vim.api.nvim_get_mode().mode') == 'i' end)
      e:lua([[require('luasnip.loaders.from_vscode').load_standalone({path=...})]], { e.project .. '/forge.code-snippets' })
      e:input('<Esc>')
      fn(e)
      for _, n in ipairs(e:lua('return vim.g.forge_e2e_notifications')) do
        assert(n.level < vim.log.levels.ERROR, n.message)
      end
    end)
    if e then
      e:snapshot(name)
      io.stdout:write('  artifacts: ' .. e.dir .. '\n')
      e:stop()
    end
    assert(ok, failure)
  end)
end

check('ввод после вызова отменяет нетронутые параметры, движение не меняет текст', function(e)
  expand(e)
  T.eq(line(e), 'combine(left, right)')
  leave_field(e)
  e:input('$a')
  e:wait('insert за вызовом', function() return e:lua('return vim.api.nvim_get_mode().mode') == 'i' end)
  T.eq(line(e), 'combine(left, right)')
  e:input(';next')
  e:wait('ввод выполнен', function() return line(e):find(';next', 1, true) ~= nil end)
  T.eq(line(e), 'combine();next')
  T.eq(e:lua([[return require('luasnip').in_snippet()]]), false)
end)

check('введённый аргумент сохраняется, нетронутый хвост удалён', function(e)
  expand(e)
  e:input('42')
  e:wait('первое поле заменено', function() return line(e) == 'combine(42, right)' end)
  leave_field(e)
  e:input('$a;')
  e:wait('ручной символ вставлен', function() return line(e):sub(-1) == ';' end)
  T.eq(line(e), 'combine(42);')
end)

check('Tab и Shift-Tab заполняют поля, завершённый вызов сохраняется', function(e)
  expand(e)
  e:input('42<Tab>')
  e:wait('второе поле выбрано', function() return e:lua('return vim.api.nvim_get_mode().mode') == 's' end)
  e:input('<S-Tab>')
  e:wait('select mode после обратного перехода', function() return e:lua('return vim.api.nvim_get_mode().mode') == 's' end)
  e:input('7<Tab>value<Tab>')
  e:wait('вызов заполнен', function() return line(e) == 'combine(7, value)' end)
  e:input(';')
  e:wait('ввод после завершённого snippet', function() return line(e):sub(-1) == ';' end)
  T.eq(line(e), 'combine(7, value);')
end)

check('явный Esc по-прежнему сворачивает активную сигнатуру', function(e)
  expand(e)
  e:input('<Esc>')
  e:wait('вызов свёрнут', function() return line(e) == 'combine()' end)
end)

check('ручной ввод в passive-поле убирает старый текст и сохраняет Unicode', function(e)
  expand(e)
  leave_field(e)
  e:input('0friзначение')
  e:wait('Unicode вставлен', function() return line(e):find('значение', 1, true) ~= nil end)
  T.eq(line(e), 'combine(значение)')
end)

check('введённый текст совпадает с default и всё равно сохраняется', function(e)
  expand(e)
  e:input('left')
  leave_field(e)
  e:input('$a;')
  e:wait('символ после вызова', function() return line(e):sub(-1) == ';' end)
  T.eq(line(e), 'combine(left);')
end)

check('очистка и новый ввод отменяются и повторяются одним undo/redo', function(e)
  expand(e)
  leave_field(e)
  e:input('$a;')
  e:wait('предложение сброшено', function() return line(e) == 'combine();' end)
  e:input('<Esc>u')
  e:wait('undo вернул состояние до ручного ввода', function() return line(e) == 'combine(left, right)' end)
  e:input('<C-r>')
  e:wait('redo восстановил ввод и отмену предложения', function() return line(e) == 'combine();' end)
end)

check('параметры до и после заполненного поля убираются без лишних запятых', function(e)
  expand(e, 'forgetriple')
  e:input('<Tab>')
  e:wait('средний параметр выбран', function() return e:lua('return vim.api.nvim_get_mode().mode') == 's' end)
  e:input('value')
  e:wait('средний параметр заполнен', function() return line(e) == 'triple(first, value, last)' end)
  leave_field(e)
  e:input('$a;')
  e:wait('ручной ввод завершён', function() return line(e):sub(-1) == ';' end)
  T.eq(line(e), 'triple(value);')
  e:input('<Esc>u')
  e:wait('несколько удалений отменены одним undo', function() return line(e) == 'triple(first, value, last)' end)
end)

check('многострочная сигнатура очищается по ranges, соседний код сохранён', function(e)
  expand(e, 'forgemulti')
  leave_field(e)
  e:input('G$a;')
  e:wait('многострочный вызов свёрнут', function()
    return e:lua([[return table.concat(vim.api.nvim_buf_get_lines(0,0,-1,false),'\n')]]) == 'multicall();'
  end)
end)

check('другой буфер и обычный код сохраняются, отмена остаётся в своём буфере', function(e)
  expand(e)
  leave_field(e)
  local original = e:lua('return vim.api.nvim_get_current_buf()')
  e:input(':new other.txt<CR>ikeep(other, text)<Esc>')
  e:wait('другой буфер заполнен', function() return line(e) == 'keep(other, text)' end)
  -- Реальная асинхронная правка скрытого буфера через публичный Neovim API.
  e:lua([[local buf=...;vim.api.nvim_buf_set_text(buf,0,8,0,12,{'edited'})]], { original })
  e:input('<C-w>p')
  e:wait('первоначальный буфер', function() return e:current_file():match('/snippet.txt$') end)
  T.eq(line(e), 'combine(edited, right)')
  e:input('$a;')
  e:wait('сигнатура первого буфера отменена', function() return line(e) == 'combine(edited);' end)
  leave_field(e)
  e:input('<C-w>p')
  e:wait('второй буфер', function() return e:current_file():match('/other.txt$') end)
  T.eq(line(e), 'keep(other, text)')
end)

check('сложный шаблон с блоком не очищается по чужим скобкам', function(e)
  expand(e, 'forgeblock')
  leave_field(e)
  e:input('Go// сохраняем')
  e:wait('новая строка введена', function() return line(e):find('сохраняем', 1, true) ~= nil end)
  T.eq(e:lua('return vim.api.nvim_buf_get_lines(0,0,-1,false)'), {
    'if (condition) {', '    body', '}', '// сохраняем',
  })
end)

T.finish()
