check('IDE-GIT-1 stage и unstage отдельного hunk',function(e)
  e:input('gg0iHUNK_A_<Esc>G0iHUNK_B_<Esc>:w<CR>')
  focus(e,' wg','NeogitStatus');row(e,'file_one.txt');e:input('<Tab>')
  e:wait('оба hunk раскрыты',function() local s=e:lua('return table.concat(vim.api.nvim_buf_get_lines(0,0,-1,false),"\\n")');return s:find('HUNK_A_',1,true) and s:find('HUNK_B_',1,true) end)
  row(e,'@@ -1,');e:input('s')
  e:wait('только первый hunk staged',function()
    local staged=git(e.project,'diff','--cached');return staged:find('HUNK_A_',1,true) and not staged:find('HUNK_B_',1,true)
  end)
  assert(git(e.project,'diff'):find('HUNK_B_',1,true))
  row(e,'Staged changes');e:input('/file_one.txt<CR><Tab>')
  e:wait('staged hunk раскрыт',function() return e:lua('return table.concat(vim.api.nvim_buf_get_lines(0,0,-1,false),"\\n")'):find('HUNK_A_',1,true)~=nil end)
  row(e,'@@ -1,');e:input('u')
  e:wait('hunk unstaged',function() return git(e.project,'diff','--cached')=='' end)
  local all=git(e.project,'diff');assert(all:find('HUNK_A_',1,true) and all:find('HUNK_B_',1,true))
end)

