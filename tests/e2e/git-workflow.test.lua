check('IDE-GIT-3 worktree пробелы visit и защита dirty delete',function(e)
  local path=e.runtime..'/worktree with space'
  create_worktree(e,path,'forge-e2e-worktree')
  local main=git(e.project,'rev-parse','HEAD')
  focus(e,'<Esc>','text');e:snapshot('worktree-code-focus');e:input(':edit file_one.txt<CR>')
  e:wait('файл из linked worktree',function() return e:current_file()==(path..'/file_one.txt'):gsub('\\','/') end)
  e:input('gg0iWORKTREE_COMMIT_<Esc>:w<CR>')
  focus(e,' wg','NeogitStatus');row(e,'file_one.txt');e:input('s')
  e:wait('worktree staged',function() return git(path,'diff','--cached','--name-only')=='file_one.txt' end)
  commit_push(e,path,'forge-e2e-worktree','forge worktree commit')
  assert(git(e.runtime..'/origin.git','show','forge-e2e-worktree:file_one.txt'):match('^WORKTREE_COMMIT_'))
  T.eq(git(e.project,'rev-parse','HEAD'),main,'main не переключился вместе с linked worktree')
  popup(e,'w','Worktree');e:input('g');picker(e,'project')
  e:wait('visit main',function() return e:lua('return vim.fn.getcwd()'):gsub('\\','/')==e.project:gsub('\\','/') end)
  status_head(e,'main')
  popup(e,'w','Worktree');e:input('g');picker(e,'worktree with space')
  e:wait('visit linked',function() return e:lua('return vim.fn.getcwd()'):gsub('\\','/')==path:gsub('\\','/') end)
  status_head(e,'forge-e2e-worktree')
  vim.fn.writefile({'DIRTY_WORKTREE_KEEP'},path..'/file_two.txt')
  popup(e,'w','Worktree');e:input('D');picker(e,'worktree with space')
  confirm(e,'Remove worktree','y');confirm(e,'modified files','n')
  e:wait('отказ force завершён',function() return e:current_ft()=='NeogitStatus' end)
  status_head(e,'main')
  T.eq(vim.fn.readfile(path..'/file_two.txt'),{'DIRTY_WORKTREE_KEEP'})
  assert(git(e.project,'worktree','list','--porcelain'):find('forge-e2e-worktree',1,true))
  -- Очистка только тестового изменения, не операция под проверкой.
  vim.fn.writefile({'second file'},path..'/file_two.txt')
  popup(e,'w','Worktree');e:input('D');picker(e,'worktree with space');confirm(e,'Remove worktree','y')
  e:wait('чистый worktree удалён',function() return vim.fn.isdirectory(path)==0 end,15000)
  assert(not git(e.project,'worktree','list','--porcelain'):find('forge-e2e-worktree',1,true))
end)

