local root=vim.fn.fnamemodify(debug.getinfo(1,'S').source:sub(2),':p:h:h:h')
package.path=root..'/tests/lib/?.lua;'..package.path
local T=require('check')
local function git(path,...)
  local args={'git','-C',path};vim.list_extend(args,{...})
  local r=vim.system(args,{text=true,env={GIT_CONFIG_NOSYSTEM='1',GIT_CONFIG_GLOBAL=vim.fn.has('win32')==1 and 'NUL' or '/dev/null'}}):wait()
  assert(r.code==0,table.concat(args,' ')..'\n'..(r.stderr or ''))
  return vim.trim(r.stdout or '')
end
local function focus(e,keys,ft)
  e:input(keys);e:wait('фокус '..keys..' → '..ft,function()
    if e:current_ft()~=ft then return false end
    if ft:match('^Neogit') then return e:lua([[return vim.fn.maparg('q','n',false,true).buffer==1]]) end
    return true
  end,10000)
end
local function row(e,pattern)
  e:wait('status содержит '..pattern,function() return e:lua('return table.concat(vim.api.nvim_buf_get_lines(0,0,-1,false),"\\n")'):find(pattern,1,true)~=nil end)
  e:input('gg/'..pattern..'<CR>')
  e:wait('строка '..pattern,function() return e:lua('return vim.api.nvim_get_current_line()'):find(pattern,1,true)~=nil end)
end
local function popup(e,key,title)
  focus(e,key,'NeogitPopup')
  e:wait(title,function() return table.concat(e.rpc:screen_lines(),'\n'):find(title,1,true)~=nil end)
end
local function status_head(e,branch)
  e:wait('status загрузил '..branch,function()
    return e:current_ft()=='NeogitStatus' and e:lua([[local branch=...;for _,line in ipairs(vim.api.nvim_buf_get_lines(0,0,-1,false)) do
      if line:match('^Head:%s+%x+%s+'..vim.pesc(branch)..'%s') then return true end end;return false]],{branch})
  end,15000)
end
local function prompt(e,pattern)
  e:wait('input '..pattern,function()
    local m=e.rpc:request('nvim_get_mode',{})
    return m.mode=='c' and e.rpc:screen_lines()[45]:find(pattern,1,true)~=nil
  end)
end
local function confirm(e,pattern,key)
  e:wait('confirm '..pattern,function()
    return e.rpc:request('nvim_get_mode',{}).mode=='r?' and table.concat(e.rpc:screen_lines(),'\n'):find(pattern,1,true)~=nil
  end)
  e:input(key)
end
local function picker(e,text)
  e:wait('настоящий picker готов к вводу',function()
    return e:current_ft()=='TelescopePrompt' and e.rpc:request('nvim_get_mode',{}).mode=='i'
  end)
  if text then e:input(text) end
  e:wait('picker выбрал '..(text or 'первый ref'),function()
    return e:lua([[local s=require('telescope.actions.state');local v=s.get_selected_entry();local text=...;return v and (text==vim.NIL or (s.get_current_picker(vim.api.nvim_get_current_buf()):_get_prompt()==text and tostring(v[1]):find(text,1,true)~=nil))]],{text or vim.NIL})
  end)
  e:input('<CR>')
end
local function pushed(e,branch)
  e:wait('уведомление о завершении push',function()
    for _,n in ipairs(e.rpc.notifications) do if n.message=='Pushed to origin/'..branch then return true end end
  end)
  if e.rpc:request('nvim_get_mode',{}).blocking then
    for _,n in ipairs(e.rpc.notifications) do assert(n.level<vim.log.levels.ERROR,n.message) end
    vim.fn.writefile(e.rpc:screen_lines(),e.dir..'/accepted-push-info.txt')
    e:input('<CR>')
  end
end
local function commit_push(e,path,branch,message)
  popup(e,'c','Commit');e:input('c')
  e:wait('настоящий commit editor готов',function()
    return e:current_ft()=='gitcommit' and e:lua([[return vim.fn.maparg('ZZ','n',false,true).buffer==1]])
  end,15000)
  e:snapshot('commit-ready');e:input('<Esc>')
  e:wait('commit editor normal',function() return e.rpc:request('nvim_get_mode',{}).mode=='n' end)
  e:input('gg0i'..message..'<Esc>')
  e:wait('сообщение введено',function() return e:lua('return vim.api.nvim_buf_get_lines(0,0,1,false)[1]')==message end)
  e:input('ZZ')
  e:wait('commit создан',function() return git(path,'log','-1','--format=%s')==message end,20000)
  e:wait('возврат в status',function() return e:current_ft()=='NeogitStatus' end)
  popup(e,'P','Push');e:input('u')
  e:wait('remote picker или push',function() return e:current_ft()=='TelescopePrompt' or git(e.runtime..'/origin.git','branch','--list',branch)~='' end,10000)
  if e:current_ft()=='TelescopePrompt' then picker(e,'origin') end
  e:wait('bare remote получил commit',function() return git(e.runtime..'/origin.git','branch','--list',branch)~='' end,20000)
  T.eq(git(e.runtime..'/origin.git','rev-parse','refs/heads/'..branch),git(path,'rev-parse','HEAD'))
  pushed(e,branch)
end
local function create_worktree(e,path,branch)
  focus(e,' wg','NeogitStatus');popup(e,'w','Worktree');e:input('W')
  prompt(e,'Create worktree')
  e:wait('отложенный path prefix введён backend',function() return e.rpc:screen_lines()[45]:gsub('\\','/'):find('forge-editor/',1,true)~=nil end)
  e:input('<C-u>'..path..'<CR>')
  picker(e,'main');prompt(e,'Create branch');e:input(branch..'<CR>')
  e:wait('linked worktree создан',function() return vim.fn.filereadable(path..'/.git')==1 end,15000)
  e:wait('status в worktree',function() return e:lua('return vim.fn.getcwd()'):gsub('\\','/')==path:gsub('\\','/') end)
  status_head(e,branch)
end
local function check(name,fn)
  if vim.env.FORGE_GIT_E2E_CASE and not name:find(vim.env.FORGE_GIT_E2E_CASE,1,true) then return end
  T.check(name,function()
    local e
    local ok,err=pcall(function()
      e=require('editor').start(root,{env={GIT_CONFIG_NOSYSTEM='1',GIT_CONFIG_GLOBAL=vim.fn.has('win32')==1 and 'NUL' or '/dev/null',GIT_TERMINAL_PROMPT='0',NEOGIT_LOG_FILE='1',NEOGIT_LOG_LEVEL='trace'},prepare=function(project,env,runtime)
        local hooks=runtime..'/empty-hooks';vim.fn.mkdir(hooks,'p')
        for k,v in pairs({['user.name']='Forge E2E',['user.email']='forge-e2e@example.invalid',['commit.gpgsign']='false',['tag.gpgsign']='false',['core.autocrlf']='false',['core.hooksPath']=hooks}) do git(project,'config',k,v) end
        git(project,'checkout','-b','main')
        local lines={};for i=1,40 do lines[i]='line '..i end
        vim.fn.writefile(lines,project..'/file_one.txt')
        git(project,'add','.');git(project,'commit','-m','fixture baseline')
        git(runtime,'init','--bare',runtime..'/origin.git')
        git(project,'remote','add','origin',runtime..'/origin.git')
        git(project,'push','-u','origin','main')
      end})
      e:wait('IDE готова',function() return e:lua('return _G.forge_e2e_observed') end,10000)
      e:input(':edit file_one.txt<CR>')
      e:wait('файл открыт',function() return e:current_file():find('file_one.txt',1,true)~=nil end)
      fn(e)
      T.eq(e:lua('return vim.g.forge_e2e_installs'),0)
      for _,n in ipairs(e.rpc.notifications) do assert(n.level<vim.log.levels.ERROR,n.message) end
    end)
    if e then
      -- Read-only наблюдения сохраняют доказательства remote/index/worktree.
      local observed={};for label,args in pairs({status={'status','--porcelain'},log={'log','--all','--oneline'},worktrees={'worktree','list','--porcelain'},remote={'ls-remote','origin'}}) do
        local good,value=pcall(git,e.project,unpack(args));observed[label]=good and value or tostring(value)
      end
      vim.fn.writefile({vim.json.encode(observed)},e.dir..'/git-observed.json')
      for _,path in ipairs(vim.fn.glob(e.runtime..'/cache/**/neogit.log',false,true)) do vim.uv.fs_copyfile(path,e.dir..'/neogit.log') end
      e:snapshot(name);io.stdout:write('  artifacts: '..e.dir..'\n');e:stop()
    end
    assert(ok,err)
  end)
end

