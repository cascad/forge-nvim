local root=vim.fn.fnamemodify(debug.getinfo(1,'S').source:sub(2),':p:h:h:h')
package.path=root..'/tests/lib/?.lua;'..package.path
local T=require('check')
local function run(args)
  local argv={vim.v.progpath,'-l',root..'/tests/diagnostics/terminal-resize.lua'}
  vim.list_extend(argv,args)
  return vim.system(argv,{cwd=root,text=true,timeout=20000}):wait()
end
T.check('SELF: NATIVE-PROBE пассивный CLI запускает чистый Neovim и убирает runtime',function()
  local result=run({'--passive','--cycles','2'})
  T.eq(result.code,0,result.stderr..result.stdout)
  local data=vim.json.decode(vim.trim(result.stdout))
  T.eq(data.completed,2);T.eq(data.cleaned,true);T.eq(data.child_exit,0)
  T.eq(vim.fn.isdirectory(data.runtime),0)
  T.eq(vim.fn.filereadable(data.artifacts..'/result.json'),1)
end)
T.check('SELF: NATIVE-PROBE invalid CLI возвращает 2',function()
  local result=run({'--cycles','0'})
  T.eq(result.code,2);T.eq(result.stdout,'')
end)
T.check('SELF: NATIVE-PROBE ошибка запуска child оставляет артефакт и убирает runtime',function()
  local result=run({'--nvim',root..'/.tests/absent-native-probe'})
  T.eq(result.code,1,result.stderr..result.stdout)
  local data=vim.json.decode(vim.trim(result.stdout))
  T.eq(data.ok,false);T.eq(data.completed,0);T.eq(data.cleaned,true)
  assert(data.error and #data.error>0)
  T.eq(vim.fn.isdirectory(data.runtime),0)
  T.eq(vim.fn.filereadable(data.artifacts..'/result.json'),1)
end)
T.finish()
