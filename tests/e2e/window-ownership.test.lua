local root=vim.fn.fnamemodify(debug.getinfo(1,'S').source:sub(2),':p:h:h:h'):gsub('\\','/')
package.path=root..'/tests/lib/?.lua;'..package.path
local T=require('check')
local e
local function check(name,fn)
  T.check(name,function()
    local ok,err=xpcall(function()
      e=require('editor').start(root)
      e:wait('IDE ready',function() return e:lua('return _G.forge_e2e_observed') end,10000)
      e:input(':edit file_one.txt<CR>');e:wait('editor ready',function() return e:current_ft()=='text' end)
      fn()
      T.eq(e:lua('return vim.g.forge_e2e_installs'),0)
      for _,n in ipairs(e.rpc.notifications) do assert(n.level<vim.log.levels.ERROR,n.message) end
    end,debug.traceback)
    if e then e:snapshot(name);io.stdout:write('  artifacts: '..e.dir..'\n');e:stop();e=nil end
    assert(ok,err)
  end)
end
local function focus(keys,ft)
  e:input(keys);e:wait('focus '..ft,function() return e:current_ft()==ft end)
end
local function tree()
  focus(' we','neo-tree');e:wait('owned Files',function() return e:lua([[local s=require('neo-tree.sources.manager').get_state_for_window()
    return vim.wo.winfixbuf and vim.b.neo_tree_source=='filesystem' and s._ready and s.tree and s.tree.bufnr==s.bufnr]]) end)
end

check('IDE-PANEL-32 native guard keeps owned buffer dirty documents and editor splits',function()
  e:input(':ASToggle<CR>');e:wait('autosave disabled for dirty fixture',function() return e:lua('return not require("auto-save").enabled()') end)
  e:input('iUNSAVED<Esc>:vsplit file_two.txt<CR>')
  e:wait('two editor splits',function() return e:lua([[local n=0;for _,w in ipairs(vim.api.nvim_list_wins()) do if require('ide.buffers').is_editor_window(w) then n=n+1 end end;return n==2]]) end)
  tree()
  local proof=e:lua([[local w,b=vim.api.nvim_get_current_win(),vim.api.nvim_get_current_buf()
    local foreign=vim.fn.bufnr('file_two.txt');local ok,err=pcall(vim.api.nvim_win_set_buf,w,foreign)
    return {blocked=not ok,error=tostring(err),same=vim.api.nvim_win_get_buf(w)==b}]])
  T.eq(proof.blocked,true);assert(proof.error:find('E1513',1,true));T.eq(proof.same,true)
  T.eq(e:lua([[local b=vim.fn.bufnr('file_one.txt');return vim.bo[b].modified and vim.api.nvim_buf_get_lines(b,0,1,false)[1]:find('UNSAVED',1,true)~=nil]]),true)
  T.eq(e:lua([[local n=0;for _,w in ipairs(vim.api.nvim_list_wins()) do if require('ide.buffers').is_editor_window(w) then n=n+1 end end;return n]]),2)
end)

check('IDE-PANEL-32 backend Files Buffers Git source transitions remain authorized',function()
  tree()
  for _,v in ipairs({{'bb','buffers'},{'bg','git_status'},{'bf','filesystem'},{'>','buffers'},{'<lt>','filesystem'}}) do
    e:input(v[1]);e:wait('source '..v[2]..' via '..v[1],function()
      return e:current_ft()=='neo-tree' and e:lua([[local source=...;local s=require('neo-tree.sources.manager').get_state_for_window()
        local mapping=vim.fn.maparg('>','n',false,true)
        return vim.b.neo_tree_source==source and vim.wo.winfixbuf and s._ready and s.tree and s.tree.bufnr==s.bufnr
          and mapping.desc=='next_source' and mapping.callback~=nil]],{v[2]})
    end)
  end
  e:input('ggl');focus('<F7>','text')
end)

check('IDE-PANEL-32 Ex edit and forced foreign buffer route to editor without losing Files',function()
  tree();local panel=e:lua('return vim.api.nvim_get_current_win()')
  e:input(':edit file_two.txt<CR>');e:wait('Ex file in editor',function() return e:current_ft()=='text' and e:current_file():find('file_two.txt',1,true) end)
  tree();e:lua([[vim.api.nvim_win_call(vim.api.nvim_get_current_win(),function() vim.cmd('edit! nested/file_three.txt') end)]])
  e:wait('forced file in editor',function() return e:current_ft()=='text' and e:current_file():find('file_three.txt',1,true) end)
  T.eq(e:lua([[local w=...;return vim.api.nvim_win_is_valid(w) and vim.bo[vim.api.nvim_win_get_buf(w)].filetype=='neo-tree' and vim.wo[w].winfixbuf]],{panel}),true)
end)

check('IDE-PANEL-32 gf from native Logs keeps view while quickfix and picker open code',function()
  e:lua([[require('forge.log_store').record(vim.fn.getcwd()..'/nested/file_three.txt',vim.log.levels.INFO,'ownership-fixture')]])
  focus(' wi','forge-logs')
  e:wait('log path ready',function()
    local row=e:lua([[for i,s in ipairs(vim.api.nvim_buf_get_lines(0,0,-1,false)) do if s:find('file_three.txt',1,true) then return i end end;return false]])
    if type(row)=='number' then e:input(row..'G$');return true end
  end)
  focus('gf','text');e:wait('gf correct file',function() return e:current_file():find('file_three.txt',1,true) end)
  T.eq(e:has_window('forge-logs'),true)
  e:input(':cexpr "file_two.txt:1:1:fixture"<CR>:copen<CR>');focus('<CR>','text')
  e:wait('quickfix file',function() return e:current_file():find('file_two.txt',1,true) end)
  tree();focus('<A-b>','TelescopePrompt');e:input('file_one<CR>');focus('<F7>','text')
end)

check('IDE-PANEL-32 Help is transient across native legacy load and save keeps live terminal',function()
  e:input(':help help<CR>');e:wait('native Help',function() return e:has_window('help') end)
  e:input(':set sessionoptions+=help<CR>:mksession! '..e.project..'/legacy.vim<CR>:helpclose<CR>:source '..e.project..'/legacy.vim<CR>')
  e:wait('legacy Help removed',function() return not e:has_window('help') end)
  focus('<F7>','text');e:input(':set sessionoptions-=help<CR>')
  focus(' wT','toggleterm')
  local job=e:lua('return vim.b.terminal_job_id')
  focus('<F7>','text');e:input(':help help<CR>')
  e:input(':lua local p=require("persistence"); p.fire("SavePre"); p.save(); p.fire("SavePost")<CR>')
  e:wait('session cleaned',function() return not e:has_window('help') end)
  T.eq(e:lua('return vim.fn.jobwait({...},0)[1]',{job}),-1,'saving must not kill terminal')
end)
check('IDE-PANEL-32 native terminal instance switch preserves both jobs and Help closes',function()
  focus(' wT','toggleterm');local first=e:lua('return vim.b.terminal_job_id')
  e:input('<Esc><Esc>:2ToggleTerm<CR>')
  e:wait('second terminal with native guard',function()
    return e:current_ft()=='toggleterm' and e:lua('return vim.b.terminal_job_id')~=first and e:lua('return vim.wo.winfixbuf')
  end)
  local second=e:lua('return vim.b.terminal_job_id')
  e:input('<Esc><Esc>:TermSelect<CR>');e:wait('native terminal selector',function() return e:current_ft()=='TelescopePrompt' end)
  e:input('1:');e:wait('terminal one selected',function()
    return e:lua([[local v=require('telescope.actions.state').get_selected_entry();return v and tostring(v.ordinal):find('1:',1,true)~=nil]])
  end);e:input('<CR>')
  e:wait('first terminal returned',function() return e:current_ft()=='toggleterm' and e:lua('return vim.b.terminal_job_id')==first end)
  T.eq(e:lua('return vim.fn.jobwait({...},0)',{first,second}),{-1,-1})
  focus('<F7>','text');e:input(':help help<CR>');e:wait('Help open',function() return e:current_ft()=='help' end)
  e:input('<F4>');e:wait('Help closed by keyboard',function() return not e:has_window('help') end)
end)
T.finish()
