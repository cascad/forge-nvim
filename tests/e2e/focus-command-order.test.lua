-- IDE-PANEL-22: normal-команды выполняются в порядке пользовательского ввода.
local root=vim.fn.fnamemodify(debug.getinfo(1,'S').source:sub(2),':p:h:h:h'):gsub('\\','/')
package.path=root..'/tests/lib/?.lua;'..package.path
local T=require('check')
local function keys(e,value)
  local before=e:lua('return _G.focus_order_done')
  e:input(value..'<F35>')
  e:wait('ввод и scheduled callbacks выполнены',function() return e:lua('return _G.focus_order_done')>before end)
end
local function files(e)
  keys(e,':badd file_two.txt<CR>')
  e:wait('файловые вкладки готовы',function()
    return e:lua([[local n=0;for _,v in ipairs(require('bufferline').get_elements().elements) do
      if vim.api.nvim_buf_get_name(v.id):match('file_[ot][nw][eo]%.txt$') then n=n+1 end end;return n==2]])
  end)
end
local function check(name,fn)
  T.check('IDE-PANEL-22 '..name,function()
    local e
    local ok,err=xpcall(function()
      e=require('editor').start(root)
      assert(vim.uv.fs_copyfile(root..'/tests/e2e/focus-command-order.test.lua',e.dir..'/focus-command-order.test.lua'))
      e:wait('Forge ready',function() return e:lua('return _G.forge_e2e_observed') end)
      e:input(':edit file_one.txt<CR>');e:wait('code',function() return e:current_ft()=='text' end)
      e:lua([[_G.focus_order_done=0;vim.keymap.set('n','<F35>',function()
        vim.schedule(function() _G.focus_order_done=_G.focus_order_done+1 end) end)]])
      fn(e)
      T.eq(e:lua('return vim.g.forge_e2e_installs'),0)
      for _,n in ipairs(e.rpc.notifications) do assert(n.level<vim.log.levels.ERROR,n.message) end
    end,debug.traceback)
    if e then
      e:snapshot('focus-command-order');io.stdout:write('  artifacts: '..e.dir..'\n')
      local stopped,cleanup=pcall(e.stop,e,not ok and err or nil)
      if not stopped then ok=false;err=tostring(err or '')..'\nCleanup: '..tostring(cleanup) end
      local exited,issue=pcall(function()
        T.eq(e.rpc.exit_code,0);T.eq(e.rpc.exit_signal,0);T.eq(e.rpc.api_errors,{})
        assert(e.rpc.shutdown_result and e.rpc.shutdown_result.ok)
      end)
      if not exited then ok=false;err=tostring(err or '')..'\nNative exit: '..tostring(issue) end
    end
    assert(ok,err)
  end)
end

for _,key in ipairs({'<F7>','<F6>'}) do
  check(key..' затем Logs сохраняет последний фокус',function(e)
    keys(e,key..' wi')
    T.eq(e:has_window('forge-logs'),true)
    T.eq(e:current_ft(),'forge-logs','поздняя команда отменила выбор Logs')
  end)
end
check('buffer cycle выполнен до выбора Logs',function(e)
  files(e);keys(e,'<C-PageDown> wi')
  T.eq(e:current_ft(),'forge-logs')
  local file=e:lua([[return vim.api.nvim_buf_get_name(vim.api.nvim_win_get_buf(require('ide').find_main_window()))]]):gsub('\\','/')
  T.eq(file,(e.project..'/file_two.txt'):gsub('\\','/'))
end)
check('close context закрывает исходный файл, сохраняя Logs',function(e)
  files(e)
  local buf=e:lua('return vim.api.nvim_get_current_buf()')
  keys(e,'<A-w> wi')
  T.eq(e:has_window('forge-logs'),true,'отложенный close закрыл Logs')
  T.eq(e:current_ft(),'forge-logs')
  T.eq(e:lua([[local b=...;return not vim.api.nvim_buf_is_valid(b) or not vim.bo[b].buflisted]],{buf}),true,'исходный файл не закрыт')
end)
check('insert F7 сохраняет текст и выходит в normal',function(e)
  e:input('iINSERT_MODE_SAFE')
  e:wait('insert',function() return e.rpc:request('nvim_get_mode',{}).mode=='i' end)
  e:input('<F7>')
  e:wait('normal code',function() return e:current_ft()=='text' and e.rpc:request('nvim_get_mode',{}).mode=='n' end)
  assert(e:lua('return vim.api.nvim_get_current_line()'):find('INSERT_MODE_SAFE',1,true))
end)
check('terminal F7 сохраняет настоящий job и историю',function(e)
  local terminal=e:lua([[vim.cmd('botright new');local b=vim.api.nvim_get_current_buf()
    local job=vim.fn.jobstart({vim.v.progpath,'--clean','--headless','-c','lua print("FOCUS_JOB_LIVE");vim.wait(60000)'},{term=true})
    assert(job>0);vim.cmd('startinsert');return {buf=b,channel=job,pid=vim.fn.jobpid(job)}]])
  e:wait('настоящий terminal input и stdout',function()
    return e.rpc:request('nvim_get_mode',{}).mode=='t' and e:lua([[return table.concat(vim.api.nvim_buf_get_lines(...,0,-1,false),'\n'):find('FOCUS_JOB_LIVE',1,true)~=nil]],{terminal.buf})
  end)
  e:input('<F7>')
  e:wait('код после terminal input',function() return e:current_ft()=='text' and e.rpc:request('nvim_get_mode',{}).mode=='n' end)
  T.eq(e:lua('return vim.fn.jobpid(...)',{terminal.channel}),terminal.pid)
  T.eq(e:lua('return vim.fn.jobwait({...},0)[1]',{terminal.channel}),-1)
  assert(e:lua([[return table.concat(vim.api.nvim_buf_get_lines(...,0,-1,false),'\n'):find('FOCUS_JOB_LIVE',1,true)~=nil]],{terminal.buf}))
  e:lua('vim.fn.jobstop(...)',{terminal.channel})
  e:wait('собственный job завершён',function() return e:lua('return vim.fn.jobwait({...},0)[1]',{terminal.channel})~=-1 end)
end)
T.finish()
