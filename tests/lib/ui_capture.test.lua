local root=vim.fn.fnamemodify(debug.getinfo(1,'S').source:sub(2),':p:h:h:h')
package.path=root..'/tests/lib/?.lua;'..package.path
local T=require('check')
T.check('SELF: UI-CAPTURE Unicode artifact path and binary handle roundtrip',function()
  local intended=assert(vim.uv.fs_realpath(vim.uv.os_tmpdir())):gsub('\\','/')
  local dir=vim.fn.tempname()..'-UI ü тест';vim.fn.mkdir(dir,'p')
  local ok,err=xpcall(function()
    local recorder=require('ui_capture').new(dir..'/redraw.jsonl')
    recorder:write({kind='native-vector',text='Ω界',handle=string.char(205,3,232)})
    assert(not recorder.error,recorder.error);recorder:close()
    local data=vim.json.decode(table.concat(vim.fn.readfile(recorder.path),'\n'))
    T.eq(data.text,'Ω界');T.eq(data.handle.__ui_bytes_hex,'cd03e8')
  end,debug.traceback)
  local resolved=assert(vim.uv.fs_realpath(dir)):gsub('\\','/')
  if vim.fn.has('win32')==1 then intended=intended:lower();resolved=resolved:lower() end
  assert(resolved:sub(1,#intended+1)==intended..'/','cleanup outside intended temp root')
  vim.fn.delete(dir,'rf');assert(ok,err)
end)
T.finish()
